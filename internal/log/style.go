// ANSI escape codes for terminal colors and styling
const (
	red     = "\x1B[31m"
	green   = "\x1B[32m"
	yellow  = "\x1B[33m"
	blue    = "\x1B[34m"
	magenta = "\x1B[35m"
	cyan    = "\x1B[36m"

	bold      = "\x1B[1m"
	dim       = "\x1B[2m"
	italic    = "\x1B[23m"
	underline = "\x1B[24m"

	reset = "\x1B[0m"
)
